async function main() {
  console.log('=== Importing 50 Quiz Questions into DOT Academy ===\n');
  let totalCreated = 0;
  let totalFailed = 0;

  for (const quizData of QUIZ_DATA) {
    const section = SECTIONS[quizData.sectionIdx];
    console.log(`\n[${quizData.sectionIdx + 1}/10] Processing: ${section.title}`);

    try {
      // Check if quiz already exists for this section
      const existing = await prisma.quiz.findFirst({
        where: { sectionId: section.id }
      });

      if (existing) {
        console.log(`  ⚠️  Quiz already exists (id: ${existing.id}), skipping...`);
        continue;
      }

      // Create the quiz with all questions
      const quiz = await prisma.quiz.create({
        data: {
          sectionId: section.id,
          passingScore: 80, // 80% passing score (4/5)
          questions: {
            create: quizData.questions.map((q, idx) => ({
              question: q.question,
              options: q.options,
              correctAnswer: q.correct,
              order: idx,
            }))
          }
        },
        include: { questions: true }
      });

      console.log(`  ✅ Created Quiz (id: ${quiz.id}) with ${quiz.questions.length} questions`);
      totalCreated += quiz.questions.length;

    } catch (err) {
      console.error(`  ❌ Error: ${err.message}`);
      totalFailed++;
    }
  }

  console.log(`\n========== SUMMARY ==========`);
  console.log(`✅ Questions created: ${totalCreated}`);
  console.log(`❌ Failed sections:   ${totalFailed}`);
  console.log(`Done!`);
}

main().catch(console.error).finally(() => prisma.$disconnect());
